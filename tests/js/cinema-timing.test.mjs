import assert from 'node:assert/strict';
import {cinemaTiming as at} from '../../static/js/cinemaTiming.js';
const lines=[{time:3,end:5,text:'A'},{time:9,end:11,text:'B'},{time:22,end:24,text:'C'}];
const saved=JSON.stringify(lines);
assert.equal(at(lines,0).state,'instrumental');
assert.equal(at(lines,1).displayLine,0);
assert.equal(at(lines,1).activeLine,null);
assert.equal(at(lines,3).activeLine,0);
assert.equal(at(lines,5).state,'short-gap');
assert.equal(at(lines,5).displayLine,0);
assert.equal(at(lines,7).displayLine,1);
assert.equal(at(lines,12).state,'instrumental');
assert.equal(at(lines,12).nextLine,2);
assert.equal(at(lines,20).state,'preview');
assert.equal(at(lines,20).activeLine,null);
assert.equal(at(lines,22).activeLine,2);
assert.equal(at(lines,24).state,'ended');
assert.equal(at(lines,24).nextLine,null);
assert.equal(at(lines,24).displayLine,null);
assert.equal(at(lines,5).displayLine,0,'backward seek');
assert.deepEqual(at(lines,4),at(lines,4),'paused clock is stable');
assert.equal(JSON.stringify(lines),saved);
assert.equal(at([],0).displayLine,null);
console.log('Cinema temporal states PASS');

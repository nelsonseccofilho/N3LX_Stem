import assert from "node:assert/strict";
import { syncStemNamesFromAPI, effectiveStemOrder, DRUM_STEMS, applyStudioLayout, STEM_DISPLAY } from "../../static/js/constants.js";
import { buildPlaybackStems } from "../../static/js/playbackStems.js";
import { effectivePitch } from "../../static/js/pitchBus.js";
const base = ["vocals", "drums", "bass", "guitar", "piano", "other"];
const slots = Array.from({length:18}, (_,i) => `studio_${String(i+1).padStart(2,"0")}`);
globalThis.fetch = async () => ({ok:true, json:async () => ({stem_names:base, extra_stem_names:["lead_vocals","backing_vocals",...DRUM_STEMS,"residual_mix","residual_drums","residual_vocals",...slots,"reaper_master"]})});
await syncStemNamesFromAPI();
const present = new Set([...base,"lead_vocals","backing_vocals",...DRUM_STEMS,"residual_mix","residual_drums","residual_vocals"]);
const order = effectiveStemOrder(present);
assert.equal(order.length,15);
assert(!order.includes("vocals") && !order.includes("drums"));
const stem = name => ({name,url:`/${name}.wav`});
const playback = buildPlaybackStems([...present].map(stem), order.map(stem),base);
assert.equal(playback.length,15);
assert(playback.filter(s=>DRUM_STEMS.includes(s.name)).every(s=>s.pitched===false));
assert.deepEqual(effectiveStemOrder(new Set(slots)),slots);
assert.deepEqual(effectiveStemOrder(new Set(["reaper_master"])),["reaper_master"]);
applyStudioLayout({labels:{studio_06:"Bumbo"},percussion_names:["studio_06"]});
assert.equal(STEM_DISPLAY.studio_06,"Bumbo");
assert.equal(effectivePitch("studio_06",5),0);
assert.equal(effectivePitch("studio_01",5),5);
applyStudioLayout(null);
assert.equal(effectivePitch("studio_06",5),5);
console.log("Studio lane routing, ordering, labels and percussion: passed");

const {setDefaultSeparationProfile} = await import("../../static/js/constants.js");
setDefaultSeparationProfile("complete");
applyStudioLayout({profile:"complete",active_names:order});
assert.deepEqual(effectiveStemOrder(present),order);
assert.equal(effectivePitch("residual_drums",5),0);
assert.equal(effectivePitch("residual_mix",5),0);
applyStudioLayout(null);
setDefaultSeparationProfile("standard");
console.log("Complete profile active lanes and residue routing: passed");
